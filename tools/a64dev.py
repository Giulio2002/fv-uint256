#!/usr/bin/env python3
"""a64seg.py: generator of Reciprocal arm64 segment lemmas with named-variable live states (arm64 twin of gseg.py).
usage: a64seg.py live CUT...        -> writes lean/Fv256/Proofs/Arm64/RecipLive.lean (defs L<off>); CUT = absolute hex address (e.g. b8e08)
State: regs by index, stack slots [sp,#d] as S.mem.readLE (S.sp.toNat + d) 8, S = the current state (sp = entry sp - 272)."""
import re, sys, os, subprocess
sys.path.insert(0, os.path.dirname(__file__))
import arm64live as AL
ROOT = '/srv/fv-uint256-wBm'
BASE = 0xb8d80
INS = AL.parse(ROOT + '/build/recip-arm64.dis')
LR, LM, LF = AL.analyse(INS)
IDX = {i[0]: k for k, i in enumerate(INS)}
STABLE = {-8, 0}
def off(a): return a - BASE
def live(addr):
    k = IDX[addr]
    regs = sorted([int(r[1:]) for r in LR[k]])
    slots = sorted([d for d in LM[k] if d not in STABLE])
    return regs, slots, LF[k]
def vname(cut, kind, key):
    return ('x%x%s%d' % (off(cut), 'r' if kind == 'r' else 'm', key))
def slot_addr(d):
    return 'S.sp.toNat + %d' % d if d >= 0 else 'S.sp.toNat - %d' % (-d)
def items(cut):
    regs, slots, f = live(cut)
    assert not f, 'flags live at %x' % cut
    return [('r', r) for r in regs] + [('m', d) for d in slots]
def Ldef(cut):
    its = items(cut)
    names = [vname(cut, k, key) for k, key in its]
    facts = []
    for (k, key), n in zip(its, names):
        if k == 'r': facts.append('(S.regs %d).toNat = %s' % (key, n))
        else: facts.append('S.mem.readLE (%s) 8 = %s' % (slot_addr(key), n))
    body = ' ∧\n  '.join(facts) if facts else 'True'
    ps = ' '.join(names)
    return 'def L%x (S : State) %s: Prop :=\n  %s\n' % (off(cut), ('(%s : Nat) ' % ps) if ps else '', body), names
def emit_live(cuts):
    out = ['import Fv256.Proofs.Arm64.RecipDefs', '', 'open Janus Janus.Arm64 Janus.GoABI Janus.Tactic Janus.Spec', '',
           'namespace Fv256.Arm64.RecipSeg', '', '/-- GENERATED by tools/a64seg.py: live state at the cut points -/']
    for c in cuts:
        d, _ = Ldef(c); out.append(d)
    out.append('end Fv256.Arm64.RecipSeg\n')
    open(ROOT + '/lean/Fv256/Proofs/Arm64/RecipLive.lean', 'w').write('\n'.join(out))
if __name__ == '__main__':
    if sys.argv[1] == 'live': emit_live([int(x, 16) for x in sys.argv[2:]])

# ---- skeleton ------------------------------------------------------------------------------------
HDR = """import Fv256.Proofs.Arm64.RecipLive

open Janus Janus.Arm64 Janus.GoABI Janus.Tactic Janus.Spec

namespace Fv256.Arm64.RecipSeg
set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false
"""
EXTRA = {0x88: ['2 ^ 63 ≤ x88m56'], 0xbc: ['xbcr0 % 2 ^ 32 = r0f xbcr3', '2 ^ 63 ≤ xbcr3']}   # extra facts about the live variables at a cut (carried by the previous segment)
def seg_stmt(A, B, q):
    names = Ldef(A)[1]
    vs = '(%s : Nat) ' % ' '.join(names) if names else ''
    ex = ''.join('(hX%d : %s) ' % (k, e) for k, e in enumerate(EXTRA.get(off(A), [])))
    return (('theorem g_%x_%x (s S : State) (hpc : S.pc = BitVec.ofNat 64 (recEntry + 0x%x)) (hs : RecPre s)\n'
            '    (hR : RecRegs s S) (hM : RecMem s S.mem) %s(hL : L%x S %s) ' + ex.replace('%', '%%') + ':\n'
            '    ReachesRet Fv256.Arm64.RecipProg.program (BitVec.ofNat 64 (recEntry + 0x%x)) S (%s) := by\n')) % (
            off(A), off(B), off(A), vs, off(A), ' '.join(names), off(B), q), names
def preamble(names_in):
    s = """  obtain ⟨h1, h2, ⟨hg1, hg2, hg3⟩, ⟨hsa, hsb, hsc, hsd⟩, hgw, hm1, hm2, hmd⟩ := hs
  have hS := hR.sp_toNat hsb
  have hacc : S.mem.accessible (S.sp.toNat - 8) 328 true = true := by
    rw [hM.2.2.accessible]; rw [show S.sp.toNat - 8 = s.sp.toNat - 280 by omega]; exact hsd
"""
    if names_in:
        hn = []
        for n in names_in: hn += ['hE_' + n, 'hB_' + n]
        s += '  obtain ⟨%s⟩ := hL\n' % ', '.join(hn)
    return s
COMMON = ['Fv256.B.rot32_and', 'BitVec.toNat_setWidth', 'BitVec.toNat_eq', 'BitVec.toNat_ushiftRight', 'BitVec.toNat_ofNat', 'Nat.shiftRight_eq_div_pow', 'BitVec.le_def', 'BitVec.lt_def', 'BitVec.toNat_sub', 'BitVec.toNat_add']
def simp_list(names_in):
    return ', '.join(['hE_' + n for n in names_in] + ['Nat.mod_eq_of_lt hB_' + n for n in names_in] + COMMON)
def emit_skel(A, B):
    st, names = seg_stmt(A, B, 'Q')
    st = st.replace('(hs : RecPre s)', '(hs : RecPre s) (Q : State → Prop)')
    body = HDR + '\nset_option maxHeartbeats 64000000 in\nset_option maxRecDepth 200000 in\n' + st + preamble(names)
    body += '  janus_run [%s] until [recEntry + 0x%x]\n  all_goals (trace_state; sorry)\n\nend Fv256.Arm64.RecipSeg\n' % (simp_list(names), off(B))
    return body
LEANCMD = ('cd %s/lean && LEAN_NUM_THREADS=8 LEAN_PATH=/srv/janus-ops/jcache-shared/v1/framework/3f949a7d48d2680d5332b3c9/.lake/build/lib/lean:%s/build/ol655 timeout 1500 memcap -m 30G '
           '/root/.elan/toolchains/leanprover--lean4---v4.34.1/bin/lean %s %s 2>&1')
def do_skel(A, B):
    p = '%s/build/skel64/A64_%x_%x.lean' % (ROOT, off(A), off(B))
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'w').write(emit_skel(A, B))
    out = subprocess.run(LEANCMD % (ROOT, ROOT, '-Dpp.deepTerms=true -Dpp.maxSteps=1000000000', p), shell=True, capture_output=True, text=True).stdout
    open(p[:-5] + '.out', 'w').write(out)
    return out
if __name__ == '__main__' and sys.argv[1] == 'skel':
    A, B = int(sys.argv[2], 16), int(sys.argv[3], 16)
    out = do_skel(A, B)
    print(out[:4000])

# ---- trace parsing ---------------------------------------------------------------------------------
def grp(e, start=0):
    d = 0
    for n in range(start, len(e)):
        if e[n] == '(': d += 1
        elif e[n] == ')':
            d -= 1
            if d == 0: return e[start + 1:n], n + 1
    raise Exception('unbalanced')
def balanced_prefix(s):
    d = 0
    for ch in s:
        if ch == '(': d += 1
        elif ch == ')': d -= 1
        if d < 0: return False
    return d == 0
def take(rest):
    if rest.startswith('('):
        g_, pos = grp(rest)
        txt = rest[:pos]
        m = re.match(r'(\.[A-Za-z]+)+', rest[pos:])
        if m: txt += m.group(0); pos += len(m.group(0))
        return txt, pos
    sp = rest.find(' ')
    if sp < 0: sp = len(rest)
    return rest[:sp], sp
def strip_par(val):
    if val.startswith('(') and val.endswith(')') and balanced_prefix(val[1:-1]): return val[1:-1]
    return val
def split_goals(t):
    """returns the list of '⊢ ReachesRet ... Q' goal texts"""
    gs = [m.start() for m in re.finditer(r'⊢ ReachesRet', t)]
    out = []
    for k, a in enumerate(gs):
        b = gs[k + 1] if k + 1 < len(gs) else len(t)
        seg = t[a:b]
        j = seg.find('\ncase ')
        out.append(seg[:j] if j >= 0 else seg)
    return out
def parse_goal(g):
    g = re.sub(r'\s+', ' ', g)
    a = g.index('regs := ') + len('regs := '); b = g.index(', sp :=')
    e = g[a:b].strip(); its = []
    while e.startswith('setReg'):
        e2 = e[len('setReg'):].lstrip()
        if e2.startswith('('): inner, pos = grp(e2)
        else:
            sp = e2.index(' '); inner = e2[:sp]; pos = sp
        rest = e2[pos:].lstrip()
        m = re.match(r'(\d+) ', rest); idx = int(m.group(1)); rest = rest[m.end():]
        val, _ = take(rest)
        its.append((idx, strip_par(val))); e = inner.strip()
    its.reverse()
    regs = {}
    for idx, v in its: regs[idx] = v
    assert e == 'S.regs', e
    c = g.index('mem := ') + len('mem := '); d_ = g.index(', dczid')
    e = g[c:d_].strip(); ws = []
    while e.startswith('('):
        inner, pos = grp(e)
        rest = e[pos:].lstrip()
        if not rest.startswith('.writeLE'): break
        rest = rest[len('.writeLE'):].lstrip()
        if rest.startswith('('): addr, p2 = grp(rest); rest = rest[p2:].lstrip()
        else:
            sp = rest.index(' '); addr = rest[:sp]; rest = rest[sp:].lstrip()
        m = re.match(r'(\d+) ', rest); n = int(m.group(1)); rest = rest[m.end():]
        val, _ = take(rest)
        ws.append((addr, n, strip_par(val))); e = inner.strip()
    if e.startswith('S.mem.writeLE'):
        rest = e[len('S.mem.writeLE'):].lstrip()
        if rest.startswith('('): addr, p2 = grp(rest); rest = rest[p2:].lstrip()
        else:
            sp = rest.index(' '); addr = rest[:sp]; rest = rest[sp:].lstrip()
        m = re.match(r'(\d+) ', rest); n = int(m.group(1)); rest = rest[m.end():]
        val, _ = take(rest)
        ws.append((addr, n, strip_par(val)))
    elif e != 'S.mem': raise Exception('mem head ' + e[:80])
    ws.reverse()
    mem = {}
    for addr, n, v in ws:
        mm = re.fullmatch(r'BitVec\.toNat S\.sp (-|\+) (\d+)', addr.strip())
        if not mm: raise Exception('addr ' + addr)
        d = int(mm.group(2)) * (-1 if mm.group(1) == '-' else 1)
        mem[d] = (n, v)
    return regs, mem

# ---- final segment emission ------------------------------------------------------------------------
def wrap_mod(e):
    e = e.strip()
    suf = ' % 18446744073709551616'
    if e.endswith(suf):
        pre = e[:-len(suf)].strip()
        if re.fullmatch(r'[A-Za-z0-9_.]+', pre) or (pre.startswith('(') and grp(pre, 0)[1] == len(pre)): return e
    return '(%s) %% 18446744073709551616' % e if re.search(r'[ ]', e) else '%s %% 18446744073709551616' % e
def nat_witness(v):
    """witness (Nat text) for a printed register value"""
    pre = 'BitVec.ofNat 64 '
    if v.startswith(pre):
        rest = v[len(pre):]
        txt, pos = take(rest)
        if pos == len(rest): return wrap_mod(strip_par(txt)), 'nat'
    return '(%s).toNat' % v, 'bv'
EXTAC = {}
BNDAC = {}
OVR = {}   # (A_off, B_off) -> {('r',i) or ('m',d): (witness text, closer)}
FACT_REG = ('first | exact bv_eq_ofNat _ | (simp only [setReg, ↓reduceIte, Nat.reduceEqDiff]; exact bv_eq_ofNat _) | '
            '(simp only [setReg, ↓reduceIte, Nat.reduceEqDiff]; exact (ofNat_mod64 _).symm) | (simp only [setReg, ↓reduceIte, Nat.reduceEqDiff]; with_reducible rfl) | '
            '(simp [setReg]; done) | (simp [setReg, BitVec.ofNat_toNat]; done)')
FACT_MEM = ('first | with_reducible rfl | (dsimp only; simp (disch := omega) only [Janus.Arm64.Memory.readLE_writeLE_of_disjoint, '
            'Janus.Arm64.Memory.readLE_writeLE_self, Nat.reducePow, Nat.mod_mod]; done)')
def emit_seg(A, B, trace_text):
    goals = split_goals(trace_text)
    parsed = [parse_goal(g) for g in goals]
    regs, mem = parsed[0]
    ovr = OVR.get((off(A), off(B)), {})
    itsA = items(A); itsB = items(B)
    namesA = Ldef(A)[1]
    nameA = {it: n for it, n in zip(itsA, namesA)}
    new_vars = []; wit = []; leaves = []; args = []; eqs = []
    for it in itsB:
        k, key = it
        n = vname(B, k, key)
        changed = (key in regs) if k == 'r' else (key in mem)
        if it in ovr:
            W, closer = ovr[it]
            new_vars.append(n); wit.append(W); args.append(n); eqs.append((n, W))
            leaves.append(closer); leaves.append(BNDAC.get(it, 'first | exact Nat.mod_lt _ (by decide) | omega'))
        elif changed:
            if k == 'r':
                W, kind = nat_witness(regs[key]); fact = FACT_REG
            else:
                nn, v = mem[key]; W = wrap_mod(v); kind = 'nat'; fact = FACT_MEM
            new_vars.append(n); wit.append(W); args.append(n); eqs.append((n, W))
            leaves.append(fact)
            leaves.append('first | exact Nat.mod_lt _ (by decide) | exact BitVec.isLt _')
        else:
            old = nameA[it]; args.append(old)
            if k == 'r':
                leaves.append('first | exact hE_%s | (simp only [setReg, ↓reduceIte, Nat.reduceEqDiff]; exact hE_%s)' % (old, old))
            else:
                leaves.append('first | exact hE_%s | (dsimp only; simp (disch := omega) only [Janus.Arm64.Memory.readLE_writeLE_of_disjoint]; exact hE_%s)' % (old, old))
            leaves.append('exact hB_%s' % old)
    eqtxt = ' ∧ '.join('%s = %s' % (n, W) for n, W in eqs)
    ex = EXTRA.get(off(B), [])
    extxt = ' ∧ '.join(ex)
    parts = [x for x in [eqtxt, extxt] if x]
    pre = ' ∧ '.join(parts) + ' ∧ ' if parts else ''
    exb = ' '.join(new_vars) if new_vars else '_u'
    post = "fun S' => ∃ %s, L%x S' %s ∧ %sRecRegs s S' ∧ RecMem s S'.mem" % (exb, off(B), ' '.join(args), pre)
    if not new_vars: post = post.replace('∃ _u, ', '')
    pdef = ("def P_%x_%x (s : State) %s(S' : State) : Prop :=\n  " % (off(A), off(B), ('(%s : Nat) ' % ' '.join(namesA)) if namesA else '')) + post[len("fun S' => "):] + '\n\n'
    st, names = seg_stmt(A, B, 'P_%x_%x s %s' % (off(A), off(B), ' '.join(namesA)))
    out = HDR + '\n' + pdef + 'set_option maxHeartbeats 64000000 in\nset_option maxRecDepth 200000 in\n' + st + preamble(names)
    out += '  janus_run [%s] until [recEntry + 0x%x]\n' % (simp_list(names), off(B))
    out += '  all_goals (\n  refine Janus.Tactic.ReachesRet.done (by first | rfl | decide | simp [recEntry, segAddr]) ?_\n  unfold P_%x_%x\n' % (off(A), off(B))
    out += '  refine ⟨%s%s?_, %s?_, ?_⟩\n' % (', '.join(wit), ', ' if wit else '', ', '.join(['?_'] * (len(eqs) + len(ex))) + (', ' if (eqs or ex) else ''))
    out += '  · unfold L%x\n    and_intros\n' % off(B)
    for l in leaves: out += '    · ' + l.replace('\n', '\n      ') + '\n'
    for n, W in eqs: out += '  · with_reducible rfl\n'
    for e in ex: out += '  · ' + EXTAC.get(e, 'omega') + '\n'
    out += '  · refine ⟨hR.1, ?_, ?_⟩\n    · first | exact hR.2.1 | (simp only [setReg, ↓reduceIte, Nat.reduceEqDiff]; exact hR.2.1)\n    · first | exact hR.2.2 | (simp only [setReg, ↓reduceIte, Nat.reduceEqDiff]; exact hR.2.2)\n'
    out += '  · dsimp only\n    repeat (refine RecMem.write ?_ _ _ _ (by omega) (by omega) (by omega) hsb)\n    exact hM\n'
    out += '  )\n\nend Fv256.Arm64.RecipSeg\n'
    return out
def do_seg(A, B, skel=True):
    if skel: do_skel(A, B)
    t = open('%s/build/skel64/A64_%x_%x.out' % (ROOT, off(A), off(B))).read()
    o = emit_seg(A, B, t)
    p = '%s/lean/Fv256/Proofs/Arm64/RecipG/G_%x_%x.lean' % (ROOT, off(A), off(B))
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'w').write(o)
    return p
if __name__ == '__main__' and sys.argv[1] == 'seg':
    A, B = int(sys.argv[2], 16), int(sys.argv[3], 16)
    p = do_seg(A, B, len(sys.argv) < 5)
    out = subprocess.run('cd %s/lean && ../build/lc.sh %s' % (ROOT, p.replace(ROOT + '/lean/', '')), shell=True, capture_output=True, text=True).stdout
    print(out[:int(os.environ.get('MAXOUT','6000'))] if out.strip() else 'OK ' + p)

# ---- normalising skeleton: post is a conjunction of `.toNat = 0` facts so that simp normalises each value ----
def emit_nskel(A, B, simp_extra=''):
    its = items(B)
    conj = []
    for k, key in its:
        if k == 'r': conj.append("(S'.regs %d).toNat = 0" % key)
        else: conj.append("S'.mem.readLE (S'.sp.toNat + %d) 8 = 0" % key)
    q = "fun S' => " + ' ∧ '.join(conj)
    st, names = seg_stmt(A, B, q)
    st = st.replace('(hs : RecPre s)', '(hs : RecPre s)', 1)
    body = HDR + '\nset_option maxHeartbeats 64000000 in\nset_option maxRecDepth 200000 in\n' + st + preamble(names)
    body += "  janus_run [%s] until [recEntry + 0x%x]\n" % (simp_list(names), off(B))
    body += ("  all_goals (\n  refine Janus.Tactic.ReachesRet.done (by first | rfl | decide | simp [recEntry, segAddr]) ?_\n"
             "  simp only [janus_post, setReg, ↓reduceIte, Nat.reduceEqDiff%s]\n  trace_state\n  sorry)\n\nend Fv256.Arm64.RecipSeg\n") % simp_extra
    return body
if __name__ == '__main__' and sys.argv[1] == 'nskel':
    A, B = int(sys.argv[2], 16), int(sys.argv[3], 16)
    p = '%s/build/skel64/N64_%x_%x.lean' % (ROOT, off(A), off(B))
    open(p, 'w').write(emit_nskel(A, B))
    out = subprocess.run(LEANCMD % (ROOT, ROOT, '-Dpp.deepTerms=true -Dpp.maxSteps=1000000000', p), shell=True, capture_output=True, text=True).stdout
    open(p[:-5] + '.out', 'w').write(out)
    print(out[:3000])
