#!/usr/bin/env python3
"""gen_libprog_arm64.py OUT.lean NAMESPACE --fn FUNC [--fn FUNC ...] -- EXTRACTED.lean EXTRACTED2.lean ...
Emit an arm64 library program `NAMESPACE.program` made of the named function segments (a segment present in several extractions must have identical words in all; each function must occur in at least one extraction of
the same harness binary: exit 1 if any base/words differ; needs at least two extractions) and the union of the extractions' stubs."""
import re, sys
args = sys.argv[1:]
out, ns = args[0], args[1]
fns, ins, base, i = [], [], None, 2
while i < len(args):
    if args[i] == "--fn": fns.append(args[i + 1]); i += 2
    elif args[i] == "--base": base = args[i + 1]; i += 2
    elif args[i] == "--": ins = args[i + 1:]; break
    else: sys.exit("bad arg " + args[i])
if len(ins) < 2: sys.exit("need at least two extractions to compare")
def parse(path):
    t = open(path).read()
    segs = {}
    for m in re.finditer(r'\{ name := "([^"]+)", base := (0x[0-9a-f]+), words := \[([^\]]*)\] \}', t):
        if m.group(1) in fns:
            segs[m.group(1)] = (m.group(2), [int(x, 16) for x in re.findall(r'0x[0-9a-f]+', m.group(3))])
    st = {m.group(1): (m.group(2), m.group(3)) for m in re.finditer(r'\{ name := "([^"]+)", addr := (0x[0-9a-f]+), kind := (\.\w+) \}', t)}
    return segs, st
ref_s, ref_st = parse(ins[0])
for p in ins[1:]:
    s, st = parse(p)
    for k, v in s.items():
        if k in ref_s and ref_s[k] != v: sys.exit("CODE WORDS DIFFER for %s between %s and %s" % (k, ins[0], p))
    ref_s.update(s)
    for k, v in st.items():
        if k in ref_st and ref_st[k] != v: sys.exit("stub %s differs between %s and %s" % (k, ins[0], p))
    ref_st.update(st)
if set(ref_s) != set(fns): sys.exit("segments missing in all extractions: %s" % (set(fns) - set(ref_s)))
L = ["import Janus"] + (["import " + base] if base else []) + ["", "/-! GENERATED by tools/gen_libprog_arm64.py from %d extractions of the same harness binary; do not edit. -/" % len(ins), "",
     "namespace " + ns, "open Janus", "", "def segments : List Segment := ["]
segs = []
for name in fns:
    b, ws = ref_s[name]
    rows = [", ".join("0x%08x" % x for x in ws[j:j + 8]) for j in range(0, len(ws), 8)]
    segs.append('  { name := "%s", base := %s, words := [\n      %s] }' % (name, b, ",\n      ".join(rows)))
L.append(",\n".join(segs) + " ]")
L += ["", "def stubs : List Stub := ["]
L.append(",\n".join('  { name := "%s", addr := %s, kind := %s }' % (k, a, kd) for k, (a, kd) in sorted(ref_st.items())) + " ]")
if base:
    L += ["", "def program : Program := { %s.program with segments := %s.segments ++ segments, stubs := %s.stubs ++ stubs }" % (base, base, base)]
else:
    L += ["", "def program : Program := { segments := segments, stubs := stubs, exitAddr := 0 }"]
L += ["", "end " + ns, ""]
open(out, "w").write("\n".join(L))
