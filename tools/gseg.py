# ---- final segment ----------------------------------------------------------------------------------
def nat_witness(v):
    """Nat witness (reduced mod 2^64) for a printed register/memory value, plus kind"""
    pre = 'BitVec.ofNat 64 '
    if v.startswith(pre):
        rest = v[len(pre):]
        txt, pos = take(rest)
        if pos == len(rest):
            e = txt
            if e.startswith('(') and balanced_prefix(e[1:-1]) and e.endswith(')'): e = e[1:-1]
            return e, 'nat', e
    mm = re.fullmatch(r'if (.*) then 1#64 else 0#64', v)
    if mm: return '(if %s then 1 else 0)' % mm.group(1), 'natb', mm.group(1)
    return '(%s).toNat' % v, 'bv', v
def top_mod(e):
    suf = ' % 18446744073709551616'
    if not e.endswith(suf): return False
    pre = e[:-len(suf)].strip()
    if pre.startswith('('):
        g_, pos = grp(pre, 0)
        return pos == len(pre)
    return re.fullmatch(r'[A-Za-z0-9_.]+', pre) is not None
def balanced_prefix(s):
    d = 0
    for ch in s:
        if ch == '(': d += 1
        elif ch == ')': d -= 1
        if d < 0: return False
    return d == 0
def wrap_mod(e):
    e = e.strip()
    if top_mod(e): return e
    return '(%s) %% 18446744073709551616' % e if re.search(r'[ ]', e) else '%s %% 18446744073709551616' % e
def emit_seg(A, B, trace_text):
    regs, mem = parse_trace(trace_text)
    itsA = items(A); itsB = items(B)
    _, namesA = Ldef(A)
    nameA = {it: n for it, n in zip(itsA, namesA)}
    new_vars = []; wit = []; leaves = []; args = []; eqs = []; eqleaves = []
    for it in itsB:
        k, key = it
        n = vname(B, k, key)
        if k == 'r':
            idx = RIDX[key]; changed = idx in regs
        else:
            changed = key in mem
        if changed:
            if k == 'r':
                w, kind, e = nat_witness(regs[idx])
                W = wrap_mod(e) if kind == 'nat' else w
                fact = 'first | with_reducible rfl | (simp only [setRegF, ↓reduceIte, Nat.reduceEqDiff]; split <;> rfl) | (simp only [setRegF, ↓reduceIte, Nat.reduceEqDiff]; with_reducible rfl) | (simp only [setRegF, ↓reduceIte, Nat.reduceEqDiff]; exact (ofNat_mod64 _).symm) | (simp [setRegF]; done) | (simp [setRegF, BitVec.ofNat_toNat]; done) | (simp only [setRegF, ↓reduceIte, Nat.reduceEqDiff]; rw [BitVec.ofNat_toNat, BitVec.setWidth_eq]; done) | (simp [setRegF]; bv_omega)'
            else:
                nn, v = mem[key]
                W = wrap_mod(v); kind = 'nat'
                fact = 'first | with_reducible rfl | (simp (disch := omega) only [Janus.Arm64.Memory.readLE_writeLE_of_disjoint, Janus.Arm64.Memory.readLE_writeLE_self, Nat.reducePow, Nat.mod_mod]; done)'
            new_vars.append(n); wit.append(W); args.append(n); eqs.append((n, W))
            if kind == 'natb':
                leaves.append('simp only [setRegF, ↓reduceIte, Nat.reduceEqDiff]; split <;> rfl')
                leaves.append('split <;> decide')
            else:
                leaves.append(fact)
                leaves.append('first | exact Nat.mod_lt _ (by decide) | exact BitVec.isLt _')
        else:
            old = nameA[it]
            args.append(old)
            if k == 'r':
                leaves.append('first | exact hE_%s | (simp only [setRegF, ↓reduceIte, Nat.reduceEqDiff]; exact hE_%s)' % (old, old))
            else:
                leaves.append('simp (disch := omega) only [Janus.Arm64.Memory.readLE_writeLE_of_disjoint]; exact hE_%s' % old)
            leaves.append('exact hB_%s' % old)
    eqtxt = ' ∧ '.join('%s = %s' % (n, W) for n, W in eqs)
    _, namesA0 = Ldef(A)
    post = 'fun S\' => ∃ %s, L%x s S\' %s ∧ %s%sRecRegs s S\' ∧ RecMem s S\'.mem y3' % (
        ' '.join(new_vars) if new_vars else '_u', B, ' '.join(args), eqtxt, ' ∧ ' if eqtxt else '')
    if not new_vars: post = post.replace('∃ _u, ', '')
    pdef = ('def P_%x_%x (s : State) (y3 : Nat) %s(S\' : State) : Prop :=\n  ' % (A, B, ('(%s : Nat) ' % ' '.join(namesA0)) if namesA0 else '')) + post[len("fun S' => "):] + '\n\n'
    st, names = seg_stmt(A, B, 'P_%x_%x s y3 %s' % (A, B, ' '.join(namesA0)))
    out = HDR + '\n' + pdef + 'set_option maxHeartbeats 64000000 in\nset_option maxRecDepth 200000 in\n' + st + preamble(A, names)
    out += '  janus64_run [%s]\n  all_goals (try janus_carry_simp)\n  all_goals (try simp only [subFlags_fst_ofNat, zero_sub64])\n  all_goals (try simp only [← BitVec.ofNat_add])\n  all_goals (try janus_carry_simp)\n' % simp_list(names, itsA)
    out += '  all_goals (\n  unfold P_%x_%x\n' % (A, B)
    out += '  refine ⟨%s%s?_, %s?_, ?_⟩\n' % (', '.join(wit), ', ' if wit else '', ', '.join(['?_'] * len(eqs)) + (', ' if eqs else ''))
    out += '  · unfold L%x\n    and_intros\n' % B
    for l in leaves: out += '    · ' + l.replace('\n', '\n      ') + '\n'
    for n, W in eqs: out += '  · with_reducible rfl\n'
    out += '  · unfold RecRegs\n    and_intros\n    · simp [setRegF, hr4]\n    · simp [setRegF, hr5]\n    · simp [setRegF, hr14]\n    · simp [hx]\n'
    out += '  · repeat (refine RecMem.write ?_ _ _ _ hlow ?_ ?_ ?_ ?_)\n    all_goals first | exact hM | omega\n'
    out += '  )\n\nend Fv256.Amd64.RecipSeg\n'
    return out, args, new_vars
def do_seg(A, B, skel=True):
    if skel: do_skel(A, B)
    t = open('%s/build/skel/RecipSkel_%x_%x.out' % (ROOT, A, B)).read()
    o, a, n = emit_seg(A, B, t)
    p = '%s/lean/Fv256/Proofs/Amd64/RecipG/G_%x_%x.lean' % (ROOT, A, B)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    o = o.replace('import Fv256.Proofs.Amd64.RecipLive', 'import Fv256.Proofs.Amd64.RecipLive')
    open(p, 'w').write(o)
    return p
if __name__ == '__main__' and sys.argv[1] == 'seg':
    A, B = int(sys.argv[2], 16), int(sys.argv[3], 16)
    p = do_seg(A, B, len(sys.argv) < 5)
    out = subprocess.run('cd %s/lean && ../build/lc.sh %s' % (ROOT, p.replace(ROOT + '/lean/', '')), shell=True, capture_output=True, text=True).stdout
    print(out[:6000] if out.strip() else 'OK ' + p)
