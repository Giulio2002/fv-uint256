#!/usr/bin/env python3
"""a64gen.py: generator of Reciprocal arm64 segment lemmas (v2: Nat-normal-form witnesses obtained from Lean's own simp).
usage: a64gen.py live CUT...      -> lean/Fv256/Arm64/RecipLive.lean
       a64gen.py nskel A B        -> normalising skeleton run (prints/saves the Nat normal form of every live item at B)
       a64gen.py seg A B [skip]   -> writes lean/Fv256/Arm64/RecipG/G_A_B.lean and compiles it
CUT/A/B = absolute hex addresses. State: regs by index, stack slots [sp,#d] as S.mem.readLE (S.sp.toNat + d) 8."""
import re, sys, os, subprocess, json
sys.path.insert(0, os.path.dirname(__file__))
import arm64live as AL
ROOT = '/srv/fv-uint256-wB5'
BASE = 0xb8d80
INS = AL.parse(ROOT + '/build/recip-arm64.dis')
LR, LM, LF = AL.analyse(INS)
IDX = {i[0]: k for k, i in enumerate(INS)}
STABLE = {-8, 0}
def off(a): return a - BASE
def live(addr):
    k = IDX[addr]
    return sorted(int(r[1:]) for r in LR[k]), sorted(d for d in LM[k] if d not in STABLE), LF[k]
def vname(cut, kind, key): return 'x%x%s%d' % (off(cut), 'r' if kind == 'r' else 'm', key)
def slot_addr(d): return 'S.sp.toNat + %d' % d if d >= 0 else 'S.sp.toNat - %d' % (-d)
def items(cut):
    regs, slots, f = live(cut)
    assert not f, 'flags live at %x' % cut
    return [('r', r) for r in regs] + [('m', d) for d in slots]
def Ldef(cut):
    its = items(cut)
    names = [vname(cut, k, key) for k, key in its]
    facts = [('(S.regs %d).toNat = %s' % (key, n)) if k == 'r' else ('S.mem.readLE (%s) 8 = %s' % (slot_addr(key), n)) for (k, key), n in zip(its, names)]
    body = ' ∧\n  '.join(facts) if facts else 'True'
    ps = ' '.join(names)
    return 'def L%x (S : State) %s: Prop :=\n  %s\n' % (off(cut), ('(%s : Nat) ' % ps) if ps else '', body), names
def emit_live(cuts):
    out = ['import Fv256.Arm64.RecipDefs', '', 'open Janus Janus.Arm64 Janus.GoABI Janus.Tactic Janus.Spec', '',
           'namespace Fv256.Arm64.RecipSeg', '', '/-- GENERATED by tools/a64gen.py: live state at the cut points -/']
    for c in cuts: out.append(Ldef(c)[0])
    out.append('end Fv256.Arm64.RecipSeg\n')
    open(ROOT + '/lean/Fv256/Arm64/RecipLive.lean', 'w').write('\n'.join(out))

HDR = """import Fv256.Arm64.RecipLive

open Janus Janus.Arm64 Janus.GoABI Janus.Tactic Janus.Spec

namespace Fv256.Arm64.RecipSeg
set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false
set_option linter.deprecated false
"""
EXTRA = {0x88: ['2 ^ 63 ≤ x88m56'], 0xbc: ['xbcr0 % 2 ^ 32 = r0f xbcr3', '2 ^ 63 ≤ xbcr3']}
EXTAC = {}       # extra-fact text -> closing tactic (default omega)
OVR = {}         # (A_off, B_off) -> {item: (witness text, closer)}
COMMON = ['Fv256.B.rot32_and', 'BitVec.toNat_setWidth', 'BitVec.toNat_eq', 'BitVec.toNat_ushiftRight', 'BitVec.toNat_ofNat', 'Nat.shiftRight_eq_div_pow',
          'BitVec.le_def', 'BitVec.lt_def', 'BitVec.toNat_sub', 'BitVec.toNat_add']
NORM = ('Janus.Tactic.sub_flags_c, BitVec.toNat_not, BitVec.toNat_ofNat, Nat.reducePow, BitVec.toNat_add, BitVec.toNat_mul, BitVec.toNat_sub, '
        'BitVec.toNat_setWidth, Fv256.B.rot32_and, Bool.toNat_true, Bool.toNat_false')
def seg_stmt(A, B, q):
    names = Ldef(A)[1]
    vs = '(%s : Nat) ' % ' '.join(names) if names else ''
    ex = ''.join('(hX%d : %s) ' % (k, e) for k, e in enumerate(EXTRA.get(off(A), [])))
    s = ('theorem g_%x_%x (s S : State) (hpc : S.pc = BitVec.ofNat 64 (recEntry + 0x%x)) (hs : RecPre s)\n'
         '    (hR : RecRegs s S) (hM : RecMem s S.mem) %s(hL : L%x S %s) ' % (off(A), off(B), off(A), vs, off(A), ' '.join(names))
         + ex + ':\n    ReachesRet Fv256.Arm64.RecipProg.program (BitVec.ofNat 64 (recEntry + 0x%x)) S (%s) := by\n' % (off(B), q))
    return s, names
def preamble(A, names_in):
    its = items(A)
    s = """  obtain ⟨h1, h2, ⟨hg1, hg2, hg3⟩, ⟨hsa, hsb, hsc, hsd⟩, hgw, hm1, hm2, hmd⟩ := hs
  have hS := hR.sp_toNat hsb
  have hacc : S.mem.accessible (S.sp.toNat - 8) 328 true = true := by
    rw [hM.2.2.accessible]; rw [show S.sp.toNat - 8 = s.sp.toNat - 280 by omega]; exact hsd
"""
    if names_in:
        s += '  obtain ⟨%s⟩ := hL\n' % ', '.join('hE_' + n for n in names_in)
    for (k, key), n in zip(its, names_in):
        if k == 'r':
            s += '  have hB_%s : %s < 2 ^ 64 := by rw [← hE_%s]; exact BitVec.isLt _\n' % (n, n, n)
            s += '  have hR_%s : S.regs %d = BitVec.ofNat 64 %s := by rw [← hE_%s]; exact bv_eq_ofNat _\n' % (n, key, n, n)
        else:
            s += '  have hB_%s : %s < 2 ^ 64 := by rw [← hE_%s]; exact Util.readLE8_lt _ _\n' % (n, n, n)
    return s
def simp_list(A, names_in):
    its = items(A)
    l = []
    for (k, key), n in zip(its, names_in):
        l.append(('hR_' if k == 'r' else 'hE_') + n)
    return ', '.join(l + ['Nat.mod_eq_of_lt hB_' + n for n in names_in] + COMMON)
def emit_skel(A, B):
    st, names = seg_stmt(A, B, 'Q')
    st = st.replace('(hs : RecPre s)', '(hs : RecPre s) (Q : State → Prop)', 1)
    return HDR + '\nset_option maxHeartbeats 64000000 in\nset_option maxRecDepth 200000 in\n' + st + preamble(A, names) + \
        '  janus_run [%s] until [recEntry + 0x%x]\n  all_goals (trace_state; sorry)\n\nend Fv256.Arm64.RecipSeg\n' % (simp_list(A, names), off(B))
LEANCMD = ('cd %s/lean && LEAN_NUM_THREADS=8 LEAN_PATH=/srv/janus-ops/jcache-shared/v1/framework/3f949a7d48d2680d5332b3c9/.lake/build/lib/lean:%s/build/ol655 timeout 2400 memcap -m 30G '
           '/root/.elan/toolchains/leanprover--lean4---v4.34.1/bin/lean %s %s 2>&1')
def run_lean(p, opts='-Dpp.deepTerms=true -Dpp.maxSteps=1000000000'):
    out = subprocess.run(LEANCMD % (ROOT, ROOT, opts, p), shell=True, capture_output=True, text=True).stdout
    open(p[:-5] + '.out', 'w').write(out)
    return out
def emit_nskel(A, B):
    its = items(B)
    conj = []
    for n, (k, key) in enumerate(its):
        if k == 'r': conj.append("(S'.regs %d).toNat = vk%d" % (key, n))
        else: conj.append("S'.mem.readLE (S'.sp.toNat + %d) 8 = vk%d" % (key, n))
    q = "fun S' => ∀ %s : Nat, " % ' '.join('vk%d' % n for n in range(len(its))) if False else "fun S' => " + ' ∧ '.join(conj)
    st, names = seg_stmt(A, B, q)
    # vk parameters as extra theorem binders
    vks = ' '.join('vk%d' % n for n in range(len(its)))
    st = st.replace('(hs : RecPre s)', '(hs : RecPre s) (%s : Nat)' % vks, 1) if its else st
    body = HDR + '\nset_option maxHeartbeats 64000000 in\nset_option maxRecDepth 200000 in\n' + st + preamble(A, names)
    body += "  janus_run [%s] until [recEntry + 0x%x]\n" % (simp_list(A, names), off(B))
    body += ("  all_goals (\n  refine Janus.Tactic.ReachesRet.done (by first | rfl | decide | simp [recEntry, segAddr]) ?_\n"
             "  simp (disch := omega) only [janus_post, setReg, ↓reduceIte, Nat.reduceEqDiff, Janus.Arm64.Memory.readLE_writeLE_of_disjoint, "
             "Janus.Arm64.Memory.readLE_writeLE_self, %s]\n  trace_state\n  sorry)\n\nend Fv256.Arm64.RecipSeg\n") % NORM
    return body
def do_nskel(A, B, skel=True):
    p = '%s/build/skel64/N2_%x_%x.lean' % (ROOT, off(A), off(B))
    os.makedirs(os.path.dirname(p), exist_ok=True)
    if skel:
        open(p, 'w').write(emit_nskel(A, B))
        return run_lean(p)
    return open(p[:-5] + '.out').read()

# ---- parsing of the normalised goal --------------------------------------------------------------
def split_top(s, sep=' ∧ '):
    out = []; d = 0; cur = ''; i = 0
    while i < len(s):
        ch = s[i]
        if ch in '(⟨[{': d += 1
        elif ch in ')⟩]}': d -= 1
        if d == 0 and s.startswith(sep, i):
            out.append(cur); cur = ''; i += len(sep); continue
        cur += ch; i += 1
    out.append(cur); return out
def goals_of(t):
    gs = [m.start() for m in re.finditer(r'⊢ ', t)]
    out = []
    for k, a in enumerate(gs):
        b = gs[k + 1] if k + 1 < len(gs) else len(t)
        seg = t[a + 2:b]
        j = seg.find('\ncase ')
        seg = seg[:j] if j >= 0 else seg
        # drop trailing diagnostics line (warning: ...)
        seg = re.split(r'\n/srv/', seg)[0]
        out.append(re.sub(r'\s+', ' ', seg).strip())
    return out
def parse_norm(out, A, B):
    """-> list of dicts per goal: item -> Nat text over old vars"""
    its = items(B); itsA = items(A); namesA = Ldef(A)[1]
    res = []
    for g in goals_of(out):
        parts = split_top(g)
        assert len(parts) == len(its), (len(parts), len(its), g[:300])
        d = {}
        for n, (it, p) in enumerate(zip(its, parts)):
            tail = ' = vk%d' % n
            assert p.endswith(tail), (p[-80:], tail)
            e = p[:-len(tail)]
            d[it] = e
        res.append(d)
    return res
def rename_refs(e, A):
    """replace register/slot reads of the state S by the live variable names of cut A"""
    its = items(A); names = Ldef(A)[1]
    for (k, key), n in zip(its, names):
        if k == 'r':
            e = e.replace('BitVec.toNat (S.regs %d)' % key, n).replace('(S.regs %d).toNat' % key, n)
        else:
            e = e.replace('S.mem.readLE (BitVec.toNat S.sp + %d) 8' % key, n)
    return e

# ---- final segment emission ------------------------------------------------------------------------
VARTOK = re.compile(r'x[0-9a-f]+[rm]\d+$')
def leaf_simp(A):
    its = items(A); names = Ldef(A)[1]
    hs = ', '.join('hE_' + n for n in names)
    base = ("janus_post, setReg, ↓reduceIte, Nat.reduceEqDiff, Janus.Arm64.Memory.readLE_writeLE_of_disjoint, "
            "Janus.Arm64.Memory.readLE_writeLE_self, " + NORM)
    return "dsimp only; simp (disch := omega) only [%s%s]" % (base, (', ' + hs) if hs else '')
def emit_seg(A, B, norm_out):
    ds = parse_norm(norm_out, A, B)
    d0 = ds[0]
    ovr = OVR.get((off(A), off(B)), {})
    if len(ds) > 1 and not all(d == d0 for d in ds[1:]) and not ovr:
        raise Exception('goals differ: need OVR for %x %x' % (off(A), off(B)))
    itsA = items(A); itsB = items(B); namesA = Ldef(A)[1]
    new_vars = []; args = []; eqs = []; wit = []; leaves = []
    for it in itsB:
        k, key = it
        n = vname(B, k, key)
        if it in ovr:
            W, closer = ovr[it]
        else:
            W = rename_refs(d0[it], A).strip(); closer = None
        if VARTOK.fullmatch(W) or re.fullmatch(r'\d+', W): args.append(W)
        else:
            new_vars.append(n); args.append(n); eqs.append((n, W)); wit.append(W)
        leaves.append(closer if closer else leaf_simp(A))
    mapB = {vname(B, k, key): a for (k, key), a in zip(itsB, args)}
    exc = EXTRA.get(off(B), [])
    ex = [re.sub(r'\bx[0-9a-f]+[rm]\d+\b', lambda m: mapB.get(m.group(0), m.group(0)), e) for e in exc]
    facts = ['%s = %s' % (n, W) for n, W in eqs] + ex
    pre = ' ∧ '.join(facts) + ' ∧ ' if facts else ''
    exb = ' '.join(new_vars)
    post = "∃ %s, L%x S' %s ∧ %sRecRegs s S' ∧ RecMem s S'.mem" % (exb, off(B), ' '.join(args), pre)
    if not new_vars: post = post.replace('∃ , ', '')
    pdef = ("def P_%x_%x (s : State) %s(S' : State) : Prop :=\n  " % (off(A), off(B), ('(%s : Nat) ' % ' '.join(namesA)) if namesA else '')) + post + '\n\n'
    st, names = seg_stmt(A, B, 'P_%x_%x s %s' % (off(A), off(B), ' '.join(namesA)))
    out = HDR + '\n' + pdef + 'set_option maxHeartbeats 64000000 in\nset_option maxRecDepth 200000 in\n' + st + preamble(A, names)
    out += '  janus_run [%s] until [recEntry + 0x%x]\n' % (simp_list(A, names), off(B))
    out += '  all_goals (\n  refine Janus.Tactic.ReachesRet.done (by first | rfl | decide | simp [recEntry, segAddr]) ?_\n  unfold P_%x_%x\n' % (off(A), off(B))
    out += '  refine ⟨%s%s?_, %s?_, ?_⟩\n' % (', '.join(wit), ', ' if wit else '', ', '.join(['?_'] * (len(eqs) + len(ex))) + (', ' if (eqs or ex) else ''))
    out += '  · unfold L%x\n    and_intros\n' % off(B)
    for l in leaves: out += '    · ' + l.replace('\n', '\n      ') + '\n'
    for n, W in eqs: out += '  · rfl\n'
    for e, ec in zip(ex, exc): out += '  · ' + EXTAC.get(ec, 'omega') + '\n'
    out += '  · refine ⟨hR.1, ?_, ?_⟩\n    · first | exact hR.2.1 | (simp only [setReg, ↓reduceIte, Nat.reduceEqDiff]; exact hR.2.1)\n    · first | exact hR.2.2 | (simp only [setReg, ↓reduceIte, Nat.reduceEqDiff]; exact hR.2.2)\n'
    out += '  · dsimp only\n    repeat (refine RecMem.write ?_ _ _ _ (by omega) (by omega) (by omega) hsb)\n    exact hM\n'
    out += '  )\n\nend Fv256.Arm64.RecipSeg\n'
    meta = dict(A=off(A), B=off(B), kind='g', invars=namesA, newvars=new_vars, outargs=args, eqs=eqs, extras=ex)
    return out, meta
def do_seg(A, B, skel=True):
    nout = do_nskel(A, B, skel)
    o, meta = emit_seg(A, B, nout)
    p = '%s/lean/Fv256/Arm64/RecipG/G_%x_%x.lean' % (ROOT, off(A), off(B))
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'w').write(o)
    json.dump(meta, open(p[:-5] + '.json', 'w'))
    return p

if __name__ == '__main__':
    cmd = sys.argv[1]
    if cmd == 'live': emit_live([int(x, 16) for x in sys.argv[2:]])
    elif cmd == 'nskel':
        A, B = int(sys.argv[2], 16), int(sys.argv[3], 16)
        out = do_nskel(A, B, len(sys.argv) < 5)
        if 'error' in out: print(out[:3000])
        for d in parse_norm(out, A, B):
            for it, e in d.items(): print(it, '=>', rename_refs(e, A)[:400]); print()

    elif cmd == 'seg':
        A, B = int(sys.argv[2], 16), int(sys.argv[3], 16)
        p = do_seg(A, B, len(sys.argv) < 5)
        out = subprocess.run('cd %s/lean && ../build/lc.sh %s' % (ROOT, p.replace(ROOT + '/lean/', '')), shell=True, capture_output=True, text=True).stdout
        print(out[:int(os.environ.get('MAXOUT', '6000'))] if out.strip() else 'OK ' + p)
