#!/usr/bin/env python3
"""gen_sfdprog_amd64.py OUT.lean EXTRACTED1.lean EXTRACTED2.lean ... : Extracted-free library program Fv256.Amd64.SfdProg
(the SetFromDecimal call tree) from >= 2 extractions of the same harness binary; refuses unless segment bytes, stubs and
contract addresses agree. Also copies dataAddr constants (from the first)."""
import re, sys
NAMES = ["github.com/holiman/uint256.(*Int).SetFromDecimal", "github.com/holiman/uint256.(*Int).fromDecimal",
         "strconv.ParseUint", "internal/strconv.ParseUint", "internal/strconv.underscoreOK", "strconv.toError",
         "runtime.decoderune", "github.com/holiman/uint256.(*Int).Mul"]
out, ins = sys.argv[1], sys.argv[2:]
assert len(ins) >= 2
def parse(p):
    t = open(p).read()
    segs = {}
    for m in re.finditer(r'def seg\d+ : Amd64\.Segment :=\s*\{ name := "([^"]+)", base := (0x[0-9a-f]+), bytes := \[([^\]]*)\] \}', t):
        if m.group(1) in NAMES:
            segs[m.group(1)] = (m.group(2), [int(x, 16) for x in re.findall(r'0x[0-9a-f]+', m.group(3))])
    stubs = re.findall(r'\{ name := "([^"]+)", addr := (0x[0-9a-f]+), kind := (\.\w+) \}', t)
    con = re.findall(r'\("(runtime\.[A-Za-z0-9]+)", (0x[0-9a-f]+)\)', t)
    return t, segs, sorted(stubs), sorted(con)
t0, s0, st0, c0 = parse(ins[0])
assert set(s0) == set(NAMES), set(NAMES) - set(s0)
for p in ins[1:]:
    t, s, st, c = parse(p)
    assert s == s0, "segment bytes differ " + p
    assert st == st0, "stubs differ " + p
    for k, v in c:
        assert dict(c0).get(k, v) == v, "contract differs " + k
L = ["import Janus", "", "/-! GENERATED by tools/gen_sfdprog_amd64.py from %d extractions of the same harness binary; do not edit. -/" % len(ins),
     "", "namespace Fv256.Amd64.SfdProg", "open Janus", "", "def segments : List Amd64.Segment := ["]
segs = []
for n in NAMES:
    b, bs = s0[n]
    rows = [", ".join("0x%02x" % x for x in bs[j:j + 16]) for j in range(0, len(bs), 16)]
    segs.append('  { name := "%s", base := %s, bytes := [\n      %s] }' % (n, b, ",\n      ".join(rows)))
L.append(",\n".join(segs) + " ]")
L.append("")
L.append("def stubs : List Stub := [")
orig = re.findall(r'\{ name := "([^"]+)", addr := (0x[0-9a-f]+), kind := (\.\w+) \}', t0)
L.append(",\n".join('  { name := "%s", addr := %s, kind := %s }' % x for x in orig) + " ]")
L.append("")
L.append("def contracts : List (String × Nat) := [")
L.append(",\n".join('  ("%s", %s)' % x for x in re.findall(r'\("(runtime\.[A-Za-z0-9]+)", (0x[0-9a-f]+)\)', t0)) + " ]")
L.append("")
L.append("def program : Amd64.Program := { segments := segments, stubs := stubs, exitAddr := 0, data := [], contracts := contracts }")
L.append("")
L.append("def entry : Nat := 0x4b4620")
L.append("")
L.append("/-- the entry of `SetFromDecimal` (consumers' `SfdSummary` entry) -/")
L.append("abbrev sfd : Nat := entry")
L.append("")
for m in re.finditer(r'def (dataAddr\.«[^»]+») : Nat := (0x[0-9a-f]+)', t0):
    L.append("def %s : Nat := %s" % (m.group(1), m.group(2)))
L.append("")
L.append("/-- ASCII-named literal copies of the addresses the statement (`SfdTopCfg.extCfg`) mentions (the auditor rejects non-ASCII names) -/")
alias = [("cfgIoEOF","io.EOF"),("cfgErrBig","github.com/holiman/uint256.ErrBig256Range"),("cfgMulTab","github.com/holiman/uint256.multipliers"),
 ("cfgNumErrType","type:strconv.NumError#3eb4e62e"),("cfgNumErrItab","go:itab.*strconv.NumError,error"),("cfgErrItab","go:itab.internal/strconv.Error,error"),
 ("cfgSynConst",".rodata#9967e7a3"),("cfgErrSyntax","strconv.ErrSyntax"),("cfgWbFlag","runtime.writeBarrier"),("cfgFnStr",".rodata#3d2a826c"),("cfgMaxStr",".rodata#575028b4")]
dd = dict((m.group(1), m.group(2)) for m in re.finditer(r'def dataAddr\.«([^»]+)» : Nat := (0x[0-9a-f]+)', t0))
for a, n in alias:
    L.append("def %s : Nat := %s" % (a, dd[n]))
L.append("")
L.append("end Fv256.Amd64.SfdProg")
open(out, "w").write("\n".join(L) + "\n")
print("ok", len(L))
